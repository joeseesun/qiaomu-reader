// The host product may pick its own interface language; Obsidian's is the fallback.
let language = "";
function setAccountLanguage(value) {
  language = String(value || "");
}
function accountText(key, ...args) {
  const text = ((language || getLanguage()).startsWith("zh") ? zh : en)[key];
  return args.length ? text.replace(/\{(\d+)\}/g, (m, i) => args[i] ?? m) : text;
}
export {
  accountText,
  setAccountLanguage
};
