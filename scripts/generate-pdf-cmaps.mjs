import fs from "node:fs";
import JSZip from "jszip";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceDir = path.join(root, "node_modules", "pdfjs-dist", "cmaps");
const output = path.join(root, "src", "pdf-cmaps-data.js");
const traditionalChineseCMap = /(?:Adobe-CNS1|B5|CNS|ETen|HK).*\.bcmap$/;

const names = fs.readdirSync(sourceDir).filter((name) => traditionalChineseCMap.test(name)).sort();
if (!names.includes("Adobe-CNS1-UCS2.bcmap")) {
  throw new Error("pdf.js Traditional Chinese CMaps were not found; run npm install first");
}

const entries = names.map((name) => {
  const encoded = fs.readFileSync(path.join(sourceDir, name)).toString("base64");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(encoded)},`;
});
const generated = [
  "// Generated by scripts/generate-pdf-cmaps.mjs from pdfjs-dist. Do not edit by hand.",
  "export const EMBEDDED_PDF_CMAPS = Object.freeze({",
  ...entries,
  "});",
  "",
].join("\n");

fs.writeFileSync(output, generated);
console.log(`embedded ${names.length} Traditional Chinese PDF CMaps`);

// These decoders are required by pdf.js 6 even for ordinary CCITT scans.
// Embed only image/color resources; JavaScript evaluation remains disabled.
const wasmNames = ["jbig2.wasm", "openjpeg.wasm", "qcms_bg.wasm"];
const wasmZip = new JSZip();
for (const name of wasmNames) {
  wasmZip.file(name, fs.readFileSync(path.join(root, "node_modules", "pdfjs-dist", "wasm", name)), { date: new Date("2000-01-01T00:00:00Z") });
}
const wasmArchive = await wasmZip.generateAsync({ type: "base64", compression: "DEFLATE", compressionOptions: { level: 9 }, platform: "UNIX" });
fs.writeFileSync(path.join(root, "src", "pdf-wasm-data.js"), [
  "// Generated by scripts/generate-pdf-cmaps.mjs from pdfjs-dist. Do not edit by hand.",
  `export const EMBEDDED_PDF_WASM_ARCHIVE = ${JSON.stringify(wasmArchive)};`,
  "",
].join("\n"));
console.log(`embedded ${wasmNames.length} compressed offline PDF image/color decoders`);
